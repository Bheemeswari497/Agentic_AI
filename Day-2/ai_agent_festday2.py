"""## 4. Create the system prompt"""

import json

SYSTEM_PROMPT = f"""
ROLE:
You are UniFest AI, a friendly college events and clubs assistant.

AVAILABLE FACTS:
{json.dumps(EVENT_INFO)}

RULES:
1. Answer only using the available event and club information.
2. Never invent event dates, venues, deadlines, or registration links.
3. If information is missing, direct the student to the Student Activity Centre.
4. Keep answers short, clear, and student-friendly.
5. Use Telugu if the student requests it.
6. Never claim a student is registered unless a registration system confirms it.
"""

print("System prompt created!")

"""## 5. Classify the student's intent"""

def classify_intent(message: str) -> str:
    messages = [
        {"role": "system", "content":
         "Classify into exactly one category: event_info, registration, club_info, complaint. Return only the category."},
        {"role": "user", "content": "When is the coding contest?"},
        {"role": "assistant", "content": "event_info"},
        {"role": "user", "content": "How do I register for InnovateX?"},
        {"role": "assistant", "content": "registration"},
        {"role": "user", "content": "Tell me about the robotics club."},
        {"role": "assistant", "content": "club_info"},
        {"role": "user", "content": "The registration page is not opening."},
        {"role": "assistant", "content": "complaint"},
        {"role": "user", "content": message}
    ]
    response = client.chat.completions.create(
        model=MODEL_NAME, temperature=0, messages=messages
    )
    return response.choices[0].message.content.strip().lower()

print(classify_intent("When will the cultural fest happen?"))

"""## 6. Extract complaint details as JSON"""

def extract_event_complaint(message: str) -> dict:
    prompt = """
Extract event-related complaint details.
Return only valid JSON with these keys:
{
  "student_name": "string or null",
  "event_name": "string or null",
  "issue": "string",
  "location": "string or null",
  "priority": "low, medium or high"
}
Do not invent missing information. Use null when unknown.
"""
    response = client.chat.completions.create(
        model=MODEL_NAME,
        temperature=0,
        messages=[
            {"role": "system", "content": prompt},
            {"role": "user", "content": message}
        ]
    )
    try:
        return json.loads(response.choices[0].message.content)
    except json.JSONDecodeError:
        return {"error": "The model did not return valid JSON"}

sample = (
    "Hi, I am Ananya from CSE. The microphone is not working "
    "at the InnovateX rehearsal in the Main Auditorium. Our practice starts in one hour."
)
result = extract_event_complaint(sample)
print(json.dumps(result, indent=2))

"""## 7. Create a logging decorator"""

import functools
import time

def log_call(func):
    @functools.wraps(func)
    def wrapper(*args, **kwargs):
        start = time.time()
        print("Running:", func.__name__)
        result = func(*args, **kwargs)
        print("Execution time:", round(time.time() - start, 4), "seconds")
        return result
    return wrapper

@log_call
def check_registration_deadline(days_before_event: int) -> dict:
    if days_before_event < 0:
        return {"error": "The event date has already passed."}
    return {
        "days_remaining": days_before_event,
        "registration_open": days_before_event >= 3
    }

print(check_registration_deadline(5))

"""## 8. Build the agent with conversation memory"""

class UniFestAgent:
    def __init__(self, system_prompt, max_turns=5):
        self.system_prompt = system_prompt
        self.max_turns = max_turns
        self.reset()

    def reset(self):
        self.history = [{"role": "system", "content": self.system_prompt}]

    def chat(self, message: str) -> str:
        if not message.strip():
            return "Please enter a message."

        self.history.append({"role": "user", "content": message})
        messages = [self.history[0]] + self.history[1:][-(self.max_turns * 2):]

        try:
            response = client.chat.completions.create(
                model=MODEL_NAME, messages=messages, temperature=0.3
            )
            reply = response.choices[0].message.content or ""
        except Exception as e:
            print("API error:", e)
            reply = "Sorry, UniFest AI is temporarily unavailable."

        self.history.append({"role": "assistant", "content": reply})
        return reply

agent = UniFestAgent(SYSTEM_PROMPT)
print("UniFest Agent Ready!")

"""## 9. Test the agent and its memory"""

