print(agent.chat("Where will it take place?"))

"""## 10. Create an interactive chat interface"""

import ipywidgets as widgets
from IPython.display import display, clear_output

chat_output = widgets.Output()
message_input = widgets.Text(
    placeholder="Ask UniFest AI about events or clubs...",
    layout=widgets.Layout(width="75%")
)
send_button = widgets.Button(description="Send", button_style="primary")
reset_button = widgets.Button(description="Reset Chat", button_style="warning")

def send_message(button):
    message = message_input.value.strip()
    if not message:
        return
    message_input.value = ""
    with chat_output:
        print("You:", message)
        print("UniFest AI:", agent.chat(message))
        print("-" * 55)

def reset_chat(button):
    agent.reset()
    with chat_output:
        clear_output()
        print("Chat history reset.")

send_button.on_click(send_message)
reset_button.on_click(reset_chat)
message_input.on_submit(send_message)

display(widgets.HTML("<h2>🎉 UniFest AI – Events & Clubs Assistant</h2>"))
display(chat_output)
display(widgets.HBox([message_input, send_button, reset_button]))

