import csv
import os

def run_tests(path="test.csv"):

    if not os.path.exists(path):
        print("Please upload test.csv first!")
        return

    with open(path, "r", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    passed = 0

    for row in rows:
        answer = chain.invoke({
            "history": [],
            "question": row["question"]
        })

        expected = row["must_include"].lower()
        ok = expected in answer.lower()

        if ok:
            passed += 1

        print(
            "PASS" if ok else "CHECK",
            "|",
            row["question"],
            "->",
            answer[:150]
        )

    print(f"\n{passed}/{len(rows)} checks passed")

run_tests()

