import chromadb

from langchain_chroma import Chroma
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_core.documents import Document

embeddings = HuggingFaceEmbeddings(
    model_name="sentence-transformers/all-MiniLM-L6-v2",
    model_kwargs={"device": "cpu"},
    encode_kwargs={"normalize_embeddings": True}
)

documents = [
    Document(
        page_content=fact,
        metadata={"fact_number": i, "business": "HackMate"}
    )
    for i, fact in enumerate(HACKMATE_FACTS, 1)
]

try:
    old_collection = Chroma(
        collection_name="hackmate_faq",
        embedding_function=embeddings
    )
    old_collection.delete_collection()
except Exception:
    pass

vector_store = Chroma.from_documents(
    documents=documents,
    embedding=embeddings,
    collection_name="hackmate_faq"
)

retriever = vector_store.as_retriever(
    search_kwargs={"k": 4}
)

print("HackMate facts stored:", vector_store._collection.count())

from langchain.tools import tool

@tool
def search_hackmate_faq(question: str) -> str:
    """
    Search HackMate knowledge about hackathon coordination,
    shortlisting email confirmations, payment reminders,
    participation responses, team follow-ups and privacy.
    """

    results = retriever.invoke(question)

    if not results:
        return "NO_KNOWLEDGE_FOUND: no matching HackMate facts."

    return "\n".join(
        f"[Fact {doc.metadata['fact_number']}] {doc.page_content}"
        for doc in results
    )

print("RAG tool ready:", search_hackmate_faq.name)

from langgraph.checkpoint.memory import InMemorySaver
from langchain.agents import create_agent

HACKMATE_SYSTEM = """
You are HackMate AI, a friendly hackathon coordination assistant
for student volunteers and event organizers.

KNOWLEDGE AND GROUNDING RULES:
- Use search_hackmate_faq for questions about coordination procedures.
- Answer policy/process questions only from retrieved knowledge.
- If the retrieved facts do not contain the answer, say:
  I don't have that information in the HackMate knowledge base.
- Never invent team IDs, team members, event dates, deadlines,
  venues, payment status, email status, or registration details.
- Treat sample knowledge as general guidance, not proof of a team's real status.
- Never claim a payment or email was verified without evidence.
- Do not expose private student phone numbers or email addresses.
- Draft polite, concise WhatsApp messages when asked.
- If a deadline is not supplied, use a placeholder or ask for it.
- Do not claim to send messages or update external trackers.
- Match the user's language when practical (English or Telugu).
"""

checkpointer = InMemorySaver()

agent = create_agent(
    model=llm,
    tools=[search_hackmate_faq],
    system_prompt=HACKMATE_SYSTEM,
    checkpointer=checkpointer
)

def chat(thread_id: str, message: str) -> str:
    result = agent.invoke(
        {"messages": [{"role": "user", "content": message}]},
        config={"configurable": {"thread_id": thread_id}}
    )
    return result["messages"][-1].content

